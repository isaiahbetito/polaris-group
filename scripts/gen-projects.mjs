/**
 * Builds the "Project by project" section on numeri.html from data/projects.json,
 * which is extracted from the client's "SITO POLARIS HR SRL.xlsx" (one sheet per plan).
 * Injects between the <!-- PROJECTS:START --> / <!-- PROJECTS:END --> markers.
 *
 * Usage: node scripts/gen-projects.mjs   (run after refreshing data/projects.json)
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const data = JSON.parse(readFileSync(join(root, 'data', 'projects.json'), 'utf8'));

const FUND = {
  FORM: { label: 'Fondimpresa', cls: 'form' },
  FLAV: { label: 'FLAV', cls: 'flav' },
};
const nf = (n) => new Intl.NumberFormat('it-IT').format(n); // 1.234 style

const card = (p) => {
  const f = FUND[p.fund] || { label: p.fund, cls: 'form' };
  const temiIt = `${p.temi} ${p.temi === 1 ? 'tema formativo' : 'temi formativi'}`;
  const temiEn = `${p.temi} ${p.temi === 1 ? 'training topic' : 'training topics'}`;
  return `        <article class="pj-card" data-year="${p.year}" data-fund="${p.fund}">
          <div class="pj-card__top">
            <span class="pj-card__code">${p.code}</span>
            <span class="pj-card__fund pj-card__fund--${f.cls}">${f.label}</span>
          </div>
          <div class="pj-card__year">${p.year}</div>
          <div class="pj-card__stats">
            <div class="pj-stat"><b>${nf(p.partecipanti)}</b><span data-it="Partecipanti" data-en="Trained">Partecipanti</span></div>
            <div class="pj-stat"><b>${nf(p.ore)}</b><span data-it="Ore" data-en="Hours">Ore</span></div>
            <div class="pj-stat"><b>${nf(p.corsi)}</b><span data-it="Corsi" data-en="Courses">Corsi</span></div>
            <div class="pj-stat"><b>${nf(p.aziende)}</b><span data-it="Aziende" data-en="Companies">Aziende</span></div>
          </div>
          <div class="pj-card__temi" data-it="${temiIt}" data-en="${temiEn}">${temiIt}</div>
        </article>`;
};

const cards = data.projects.map(card).join('\n');
const n = data.count;

const section = `  <!-- PROJECTS:START -->
  <!-- Generated by scripts/gen-projects.mjs from data/projects.json — do not edit by hand -->
  <section class="section section--cream reveal">
    <div class="container">
      <div class="section__head pj-head">
        <span class="eyebrow eyebrow--center" data-it="Progetto per progetto" data-en="Project by project">Progetto per progetto</span>
        <h2 data-it-html="Ogni piano, nel <em class='hl'>dettaglio</em>." data-en-html="Every plan, in <em class='hl'>detail</em>.">Ogni piano, nel <em class="hl">dettaglio</em>.</h2>
        <p data-it="I ${n} piani formativi gestiti nel biennio 2024–2025, ciascuno con i suoi corsi, ore, aziende e partecipanti." data-en="The ${n} training plans managed across 2024–2025, each with its own courses, hours, companies and participants.">I ${n} piani formativi gestiti nel biennio 2024–2025, ciascuno con i suoi corsi, ore, aziende e partecipanti.</p>
      </div>
      <div class="pj-filters" data-pj-filters>
        <button class="pj-chip is-active" type="button" data-pj="all" data-it="Tutti" data-en="All">Tutti</button>
        <button class="pj-chip" type="button" data-pj="y2024">2024</button>
        <button class="pj-chip" type="button" data-pj="y2025">2025</button>
        <button class="pj-chip" type="button" data-pj="fFORM" data-it="Fondimpresa" data-en="Fondimpresa">Fondimpresa</button>
        <button class="pj-chip" type="button" data-pj="fFLAV" data-it="FLAV" data-en="FLAV">FLAV</button>
      </div>
      <div class="pj-grid" data-pj-grid>
${cards}
      </div>
    </div>
    <script>
      (function () {
        var wrap = document.querySelector('[data-pj-filters]');
        if (!wrap) return;
        var chips = wrap.querySelectorAll('[data-pj]');
        var cards = document.querySelectorAll('[data-pj-grid] .pj-card');
        chips.forEach(function (c) {
          c.addEventListener('click', function () {
            chips.forEach(function (x) { x.classList.remove('is-active'); });
            c.classList.add('is-active');
            var k = c.getAttribute('data-pj');
            cards.forEach(function (card) {
              var show = k === 'all'
                || (k.charAt(0) === 'y' && card.getAttribute('data-year') === k.slice(1))
                || (k.charAt(0) === 'f' && card.getAttribute('data-fund') === k.slice(1));
              card.classList.toggle('is-hidden', !show);
            });
          });
        });
      })();
    </script>
  </section>
  <!-- PROJECTS:END -->`;

const file = join(root, 'numeri.html');
let html = readFileSync(file, 'utf8');
const re = /  <!-- PROJECTS:START -->[\s\S]*?  <!-- PROJECTS:END -->/;
if (!re.test(html)) { console.error('Markers PROJECTS:START/END not found in numeri.html'); process.exit(1); }
html = html.replace(re, section);
writeFileSync(file, html);
console.log(`Injected ${n} project cards into numeri.html`);
